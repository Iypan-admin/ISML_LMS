export async function GET() {
  try {
    const res = await fetch('https://ismllms-production.up.railway.app/api/portals/curriculum-matrices/colleges', {
      headers: { 'Content-Type': 'application/json' },
      cache: 'no-store',
    }).catch(() => null);

    if (res && res.ok) {
      const json = await res.json();
      if (json?.status === 'success' && Array.isArray(json.data) && json.data.length > 0) {
        return NextResponse.json({ status: 'success', data: json.data });
      }
    }
  } catch {}

  return NextResponse.json({ status: 'success', data: fallbackCollegeMatrices });
}

